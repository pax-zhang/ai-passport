static const char *const *const TAB[APP_LANG_N] = { EN, ZH };

_Static_assert(sizeof(EN) / sizeof(EN[0]) == APP_STR_COUNT, "EN strings");
_Static_assert(sizeof(ZH) / sizeof(ZH[0]) == APP_STR_COUNT, "ZH strings");

const char *app_str(app_str_id_t id)
{
    if ((unsigned)id >= APP_STR_COUNT) return "";
    return TAB[s_lang][id];
}

const char *app_str_onoff(bool on)
{
    return app_str(on ? APP_STR_ON : APP_STR_OFF);
}

app_lang_t app_lang(void)
{
    return s_lang;
}

void app_lang_set(app_lang_t lang)
{
    if ((unsigned)lang >= APP_LANG_N) lang = APP_LANG_EN;
    s_lang = lang;
}

const char *app_lang_name(app_lang_t lang)
{
    if (lang == APP_LANG_ZH) return "简体中文";
    return "English";
}

const char *app_lang_html(void)
{
    return s_lang == APP_LANG_ZH ? "zh-CN" : "en";
}
